// Реальные IPC и запись файлов; ответы диалогов подставляются только в режиме --run.
const { app, test } = window.__phaint;
const native = window.phaintNative;
const assert = (ok, message) => { if (!ok) throw new Error(message); };
const choose = choices => native.testFiles('choices', { choices });
const prepare = (name, text) => native.testFiles('prepare', { name, text });
const read = name => native.testFiles('read', { name });
const waitFile = async () => { for (let i=0; i<500 && app.files.busy; i++) await test.sleep(10); assert(!app.files.busy, 'файловая операция завершилась'); };
const draw = async (y=180) => test.pen([[180,y,.1],[205,y-8,.4],[240,y+6,.9],[280,y,.3]],8);
assert(app.doc.size === 0 && !app.files.dirty, 'запуск с пустым холстом');
// Здесь проверяется внешний простой контур; сетку отдельно проверяют grid-crop/ui-files.
app.settings.grid.save=false;
await draw();
const original = [...app.doc.values()][0];
const points = [...original.pts];
await choose({ saves: ['урок.svg'] });
test.key('KeyS', { metaKey:true }); await waitFile();
assert(!app.files.dirty && app.files.file.name === 'урок.svg', 'Cmd+S сохранил SVG');
const svg = await read('урок.svg');
assert(svg.includes('<path ') && svg.includes('<metadata '), 'обычный вектор + данные пера');
await draw(250); assert(app.files.dirty, 'новый штрих меняет документ');
test.key('KeyZ'); assert(!app.files.dirty, 'отмена к сохранённому снимает изменения');
test.key('KeyY'); assert(app.files.dirty, 'повтор возвращает изменения');
await app.files.backup();
assert((await app.platform.files.recoveryRead())?.data, 'резервная копия записана');
await choose({ opens: ['урок.svg'], unsaved: ['cancel'] });
assert(!await app.files.open() && app.doc.size === 2, 'отмена открытия сохраняет рисунок');
await choose({ opens: ['урок.svg'], unsaved: ['discard'] });
assert(await app.files.open() && app.doc.size === 1 && !app.files.dirty, 'открытие заменяет рисунок');
assert(JSON.stringify([...app.doc.values()][0].pts) === JSON.stringify(original.pts), 'все точки и нажим сохранены точно');
assert(!app.history.canUndo && !app.history.canRedo, 'история старого файла освобождена');
assert(await app.platform.files.recoveryRead() === null, 'устаревшая резервная копия удалена');
await draw(250);
await choose({ unsaved: ['save'], saves: [null] });
// У уже открытого файла Cmd+S не вызывает диалог. Проверяем отмену отдельного «Сохранить как».
assert(!await app.files.save(true) && app.files.dirty, 'отмена сохранения не снимает изменения');
await prepare('ошибка.svg', '<svg broken');
await choose({ opens: ['ошибка.svg'] });
assert(!await app.files.open() && app.doc.size === 2, 'повреждённый файл не уничтожает текущий');
await prepare('ссылка.svg', '<svg xmlns="http://www.w3.org/2000/svg"><image href="https://example.com/photo.png" width="20" height="20"/></svg>');
await choose({ opens: ['ссылка.svg'] });
assert(!await app.files.open() && app.doc.size === 2, 'внешние ресурсы не загружаются');
// Другая программа успела изменить открытый файл: старое содержимое не затираем.
const changedSvg = svg.replace(`fill="${original.color}"`,'fill="#c9514e"');
await prepare('урок.svg', changedSvg);
assert(!await app.files.save() && app.files.dirty, 'внешняя запись защищена от перезаписи');
assert(await read('урок.svg') === changedSvg, 'внешние изменения остались на диске');
await choose({ opens: ['урок.svg'], unsaved: ['discard'] });
assert(await app.files.open(), 'изменённый SVG открылся');
const imported = [...app.doc.values()][0];
assert(imported.kind === 'vector' && (imported.fill==='#c9514e'||imported.fill==='rgb(201, 81, 78)'), 'видимые внешние правки важнее старой metadata');
await draw(340);
await choose({ saves: ['обмен.svg'] });
assert(await app.files.save(true), 'импорт + новый штрих сохраняются');
const exchanged = await read('обмен.svg');
assert((exchanged.includes('#c9514e')||exchanged.includes('rgb(201, 81, 78)')) && !exchanged.includes('<image '), 'чужая графика остаётся векторной');
await choose({ opens: ['обмен.svg'] });
assert(await app.files.open() && app.doc.size === 2, 'повторное открытие смешанного рисунка');
// Градиенты и локальные ссылки, в том числе в кавычках, не теряются.
await prepare('градиент.svg', '<svg xmlns="http://www.w3.org/2000/svg" width="320" height="200" viewBox="0 0 320 200"><defs><linearGradient id="g"><stop stop-color="#3f6fb5"/><stop offset="1" stop-color="#c9514e"/></linearGradient></defs><rect x="10" y="10" width="300" height="180" style="fill:url(\'\u0023g\')"/><text x="25" y="105" font-size="28" fill="white">SVG: А &amp; Б</text></svg>');
await choose({ opens: ['градиент.svg'] });
assert(await app.files.open(), 'SVG с градиентом и текстом открылся');
await test.idle(); await test.shot('import');
await draw(500);
await app.files.backup();
const backup = await app.platform.files.recoveryRead();
assert(backup && backup.data.includes('svg'), 'резервная копия содержит импортированный вектор');
await choose({ unsaved: ['cancel'] });
assert(!await app.files.newDocument() && app.doc.size === 3, 'отмена нового документа сохраняет градиент, текст и штрих');
await choose({ unsaved: ['discard'] });
assert(await app.files.newDocument() && app.doc.size === 0 && !app.files.dirty, 'новый пустой документ');
assert(await app.platform.files.recoveryRead() === null, 'после отказа от изменений копия удалена');
// Пока сохраняется снимок, разрешено писать дальше; новые штрихи остаются несохранёнными.
await draw();
await choose({ saves: ['во-время-письма.svg'] });
const workerClass=Object.getPrototypeOf(app.files.worker),stream = workerClass.streamSvg;
workerClass.streamSvg = async function(...args) { await test.sleep(100); return stream.apply(this,args); };
const saving = app.files.save();
await test.sleep(20); await draw(300); await saving;
workerClass.streamSvg = stream;
assert(app.doc.size === 2 && app.files.dirty, 'штрих во время сохранения не помечен сохранённым');
await choose({ opens: ['во-время-письма.svg'], unsaved: ['discard'] });
assert(await app.files.open() && app.doc.size === 1, 'в SVG записан именно снятый снимок');
return { ok:true, savedPoints:points.length/3, svgBytes:svg.length, exchangedBytes:exchanged.length, expectedErrors:await native.testFiles('errors') };
