// Ластик, отмена прохода, сохранение фрагментов и быстрая палитра через настоящие события DOM.
const {app,test}=window.__phaint;
const assert=(ok,msg)=>{if(!ok)throw new Error(msg);};
const key=(code)=>test.key(code,{metaKey:true,shiftKey:true});
app.settings.grid.enabled=false; app.settings.pen.smoothing=0; app.settings.pen.width=8;
const scene=document.getElementById('scene');
const pixel=(x,y)=>scene.getContext('2d').getImageData(Math.round(x*app.view.dpr),Math.round(y*app.view.dpr),1,1).data;
const ink=(x,y)=>pixel(x,y)[0]<120;
await test.pen([[200,240,.5],[800,240,.5]],4); await test.idle();
const original=[...app.doc.values()][0];
await window.phaintNative.testFiles('choices',{choices:{saves:['ластик.svg']}});
assert(await app.files.save(),'сохранён исходный рисунок');
key('KeyE'); assert(app.tool.id==='eraser','Cmd+Shift+E включает ластик');
const width=app.settings.eraser.width;
test.key('F1'); assert(app.settings.eraser.width<width && app.settings.pen.width===8,'размер ластика независим от ручки');
test.key('F2'); app.settings.eraser.width=24; app.updateCursor();
test.pointer('pointerdown',500,180,.5); test.pointer('pointermove',500,300,.5);
await test.idle();
assert(ink(300,240) && !ink(500,240) && ink(700,240),'ластик сразу стирает участок, оставляя оба конца');
test.pointer('pointermove',650,300,.5); test.pointer('pointermove',650,180,.5); test.pointer('pointerup',650,180,0);
await test.idle();
assert(app.doc.size===3 && app.files.dirty,'один проход сделал три фрагмента');
await test.shot('erased');
test.key('KeyZ',{metaKey:true}); await test.idle();
assert(app.doc.size===1 && [...app.doc.values()][0]===original && !app.files.dirty,'Cmd+Z возвращает весь проход и сохранённое состояние');
test.key('KeyZ',{metaKey:true,shiftKey:true}); await test.idle();
assert(app.doc.size===3 && !ink(500,240) && !ink(650,240),'повтор восстанавливает разрезы');
const cut=[...app.doc.values()];
test.pointer('pointerdown',300,240,.5); test.pointer('pointermove',300,260,.5); test.key('Escape'); await test.idle();
assert(app.doc.size===3 && cut.every(o=>[...app.doc.values()].includes(o)),'Esc отменяет текущий проход');
assert(await app.files.save(),'сохранены разрезанные штрихи');
await window.phaintNative.testFiles('choices',{choices:{opens:['ластик.svg']}});
assert(await app.files.open() && app.doc.size===3,'SVG открыл фрагменты'); await test.idle();
assert(!ink(500,240) && !ink(650,240),'стёртые участки не возвращаются после открытия SVG');
key('KeyD'); assert(app.tool.id==='pen','Cmd+Shift+D включает ручку');
const colors=app.settings.palette;
test.key('Tab'); assert(app.palette.open && app.currentColor===colors[1],'первое Tab сразу меняет цвет');
test.key('Tab',{repeat:true}); assert(app.currentColor===colors[1],'удержание Tab не листает самопроизвольно');
test.key('Tab',{shiftKey:true}); assert(app.palette.open && app.currentColor===colors[1] && !app.palette.el.querySelector('.palette-label').hidden,'Shift+Tab открывает все цвета без изменения цвета');
app.palette.hide(); test.key('Tab',{shiftKey:true}); assert(app.palette.open,'Shift+Tab открывает закрытую палитру');app.palette.el.querySelectorAll('button')[2].click();
const grid=app.settings.grid.enabled; test.key('KeyG'); assert(app.settings.grid.enabled!==grid,'G переключает сетку'); test.key('KeyG'); assert(app.settings.grid.enabled===grid,'повторное G возвращает сетку');
for(let i=0;i<3;i++){
  test.key('Tab'); assert(app.currentColor===colors[i],'повторное Tab выбирает следующий цвет');
  await test.pen([[200,340+i*60,.5],[800,340+i*60,.5]],3);
  assert([...app.doc.values()].at(-1).color===colors[i],'штрих получает выбранный цвет');
}
await test.sleep(650); test.key('Tab'); await test.sleep(500);
assert(app.palette.open && app.currentColor===colors[0],'таймер продлевается после повторного нажатия');
await test.shot('palette'); await test.sleep(550);
assert(!app.palette.open,'палитра исчезает через секунду');
test.key('Tab'); app.palette.el.querySelectorAll('button')[1].click();
assert(app.currentColor===colors[1],'цвет выбирается нажатием кружка');
// Выбор цвета во время письма не перекрашивает уже начатую линию.
test.pointer('pointerdown',900,200,.5); test.pointer('pointermove',1000,220,.5);
test.key('Tab'); test.pointer('pointerup',1050,220,0);
assert([...app.doc.values()].at(-1).color===colors[1] && app.currentColor===colors[2],'цвет меняется со следующего штриха');
test.key('F9'); assert(!app.palette.open && app.toolbar.el.hidden,'F9 закрывает палитру вместе с интерфейсом');
test.key('F9'); await test.idle();
return {ok:true,objects:app.doc.size,colors};
