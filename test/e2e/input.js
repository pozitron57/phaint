// Регрессии последнего отрезка, курсора, F9 и перемещения холста пробелом.
const { app, test } = window.__phaint;
const assert = (ok, message) => { if (!ok) throw new Error(message); };
const live = document.getElementById('live');
test.key('KeyB'); test.key('F12'); test.key('F9');
assert(app.toolbar.el.hidden && !app.panels.brush.open && !app.panels.background.open && !app.settings.ui.debug, 'F9 закрывает весь интерфейс');
test.key('F9'); assert(!app.toolbar.el.hidden, 'повторный F9 показывает панель');
test.pointer('pointerdown',180,180,.4);
assert(getComputedStyle(live).cursor !== 'none', 'курсор виден при рисовании');
test.pointer('pointermove',230,180,.7);
test.pointer('pointerup',310,180,0);
const stroke = [...app.doc.values()][0];
assert(Math.abs(stroke.ox + stroke.pts.at(-3) - 310) < .01, 'координата отрыва вошла в штрих');
assert(stroke.pts.at(-1) > 2, 'нулевое нажатие при отрыве не обрубает толщину');
const before = app.view.toScreen(0,0);
test.key('Space'); await test.pen([[200,250,.5],[300,290,.5]],8);
window.dispatchEvent(new KeyboardEvent('keyup',{code:'Space',key:' ',bubbles:true}));
const after = app.view.toScreen(0,0);
assert(app.doc.size === 1 && after.x-before.x === 100 && after.y-before.y === 40, 'пробел двигает холст без штриха');
test.pointer('pointerdown',400,400,.5); test.pointer('pointermove',450,400,.5); test.key('Escape');
test.pointer('pointerup',450,400,0);
assert(app.doc.size === 1 && !app.input.drawing, 'явная отмена через Esc не создаёт объект');
test.pointer('pointerdown',400,400,.5);
const scale = app.view.scale; test.key('Equal',{ctrlKey:true});
assert(app.view.scale === scale,'масштаб не меняется под рисующим пером');
test.pointer('pointerup',430,400,0);
await test.idle(); await test.shot('fixed');
const frames = app.renderer.frames;
await test.sleep(1000);
assert(app.renderer.frames === frames,'отрисовщик не просыпается на неподвижном холсте');
return { ok:true, objects:app.doc.size, idleFrames:app.renderer.frames-frames };
